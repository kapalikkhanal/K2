#!/usr/bin/env python3
"""Convert a K2 policy ONNX into a C header for the ESP32-S3.

The exported graph is a fixed 4-layer MLP with an input normalizer:

    x = (obs - mean) / std
    x = elu(W0 x + b0) -> elu(W2 x + b2) -> elu(W4 x + b4) -> W6 x + b6

so there is nothing to interpret at runtime and no inference engine is needed.
A reference input/output pair is embedded too, letting the firmware prove it
reproduces onnxruntime rather than merely producing plausible numbers.

    python tools/export_policy.py ../policies/turn_v11_iter3400.onnx src/policy_weights.h
"""
import sys
import numpy as np
import onnx
from onnx import numpy_helper


def emit(fh, name, arr):
    flat = arr.astype(np.float32).ravel()
    fh.write(f"static const float {name}[{flat.size}] = {{\n")
    for i in range(0, flat.size, 8):
        # %.9g round-trips float32 exactly.
        values = []
        for v in flat[i:i + 8]:
            text = f"{v:.9g}"
            if "." not in text and "e" not in text:
                text += ".0"
            values.append(text + "f")
        fh.write("  " + ",".join(values) + ",\n")
    fh.write("};\n\n")


def main(src, dst):
    model = onnx.load(src)
    init = {i.name: numpy_helper.to_array(i) for i in model.graph.initializer}

    mean = init["obs_normalizer._mean"].ravel()
    std = init[[k for k in init if k.startswith("onnx::Div")][0]].ravel()
    layers = [(init[f"mlp.{i}.weight"], init[f"mlp.{i}.bias"]) for i in (0, 2, 4, 6)]

    obs_dim = mean.size
    act_dim = layers[-1][1].size

    # Deterministic probe vector, spread over a plausible observation range.
    rng = np.random.default_rng(0)
    probe = rng.uniform(-1.0, 1.0, obs_dim).astype(np.float32)

    import onnxruntime as ort
    sess = ort.InferenceSession(src, providers=["CPUExecutionProvider"])
    expected = sess.run(None, {"obs": probe.reshape(1, -1)})[0].ravel()

    total = mean.size + std.size + sum(w.size + b.size for w, b in layers)

    with open(dst, "w") as fh:
        fh.write("// Generated by tools/export_policy.py -- do not edit.\n")
        fh.write(f"// source: {src}\n")
        fh.write(f"// {obs_dim} -> " + " -> ".join(str(w.shape[0]) for w, _ in layers) + "\n")
        fh.write(f"// {total} parameters, {total * 4} bytes as float32\n#pragma once\n\n")
        fh.write(f"#define POLICY_OBS_DIM {obs_dim}\n")
        fh.write(f"#define POLICY_ACT_DIM {act_dim}\n")
        fh.write(f"#define POLICY_PARAM_COUNT {total}\n\n")
        for i, (w, _) in enumerate(layers):
            fh.write(f"#define L{i}_OUT {w.shape[0]}\n#define L{i}_IN {w.shape[1]}\n")
        fh.write("\n")
        emit(fh, "P_MEAN", mean)
        emit(fh, "P_STD", std)
        for i, (w, b) in enumerate(layers):
            emit(fh, f"P_W{i}", w)   # row-major (out, in); ONNX Gemm transB=1
            emit(fh, f"P_B{i}", b)
        emit(fh, "P_PROBE_OBS", probe)
        emit(fh, "P_PROBE_EXPECTED", expected)

    print(f"{dst}: {total} params, obs {obs_dim} -> act {act_dim}")
    print("expected[:4] =", np.array2string(expected[:4], precision=6))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
