#!/usr/bin/env python3
"""Emit K2's joint mapping, calibration and policy constants as a C header.

Everything here is data the firmware must agree with byte-for-byte or the
observation is silently wrong: SIM_ORDER, the servo id per joint, the per-joint
home offset and sign from calibration.json, and the command/gait constants from
the policy's own ONNX metadata.
"""
import sys, json
sys.path.insert(0, ".")
import numpy as np, onnx
from hardware import k2_conventions as C

model = onnx.load(sys.argv[1])
md = {p.key: p.value for p in model.metadata_props}
# Both staged lateral and full policies use this deployment layout. Smoothing
# is supplied by CommandProfile in firmware; it need not be a training label.
profile = md.get('gait_command_profile', '')
if profile not in ('', 'smooth_full_v1'):
    raise ValueError(f'Unsupported command profile: {profile}')
if (md.get('gait_channel5') != 'lateral_velocity' or
    md.get('gait_command_dim') != '6' or
    md.get('heading_observation_dim') != '2' or
    len(model.graph.input) != 1 or
    model.graph.input[0].type.tensor_type.shape.dim[-1].dim_value != 50):
    raise ValueError('This firmware requires a 50-input lateral policy with heading observations')
if md.get('joint_names', '').split(',') != [C.JOINT_TO_MJCF[j] for j in C.SIM_ORDER]:
    raise ValueError('Policy joint order does not match firmware SIM_ORDER')
if md.get('observation_names') != 'base_ang_vel,projected_gravity,joint_pos,joint_vel,actions,heading,gait':
    raise ValueError('Policy observation order does not match firmware')
if float(md.get('gait_lateral_positive_phase', 'nan')) != 0:
    raise ValueError('Firmware requires lateral positive phase zero')
if not 0 <= float(md.get('gait_rel_march_envs', 'nan')) < 1:
    raise ValueError('Firmware requires a policy trained with HOLD')
if not profile:
    print('Staged lateral policy: using firmware command smoothing and double-support stopping.')
calib = C.load_calibration() if hasattr(C, "load_calibration") else None
if calib is None:
    calib = json.load(open("hardware/calibration.json"))

home = calib["home_raw"]; sign = calib["sign"]
default_pos = [float(x) for x in md["default_joint_pos"].split(",")]

def fl(v):
    # "%.9g" % 0.0 gives "0", and "0f" is not a valid C float literal.
    t = "%.9g" % v
    if "." not in t and "e" not in t and "inf" not in t and "nan" not in t:
        t += ".0"
    return t + "f"

def arr(name, vals, fmt="%.9gf"):
    body = ", ".join(fl(v) if "f" in fmt else str(v) for v in vals)
    return f"static const {'float' if 'f' in fmt else 'int16_t'} {name}[12] = {{{body}}};\n"

with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/export_k2_config.py -- do not edit.\n#pragma once\n\n")
    f.write("// SIM_ORDER: " + ", ".join(C.SIM_ORDER) + "\n")
    f.write(f"#define K2_RAD_PER_COUNT {C.RAD_PER_COUNT:.9g}f\n")
    f.write(f"#define K2_ACTION_SCALE {float(md['action_scale']):.9g}f\n")
    f.write(f"#define K2_GAIT_FREQ_HZ {float(md['gait_frequency_hz']):.9g}f\n")
    f.write(f"#define K2_GAIT_TRANSITION_S {fl(float(md['gait_transition_time_s']))}\n")
    f.write(f"#define K2_VX_MAX {float(md['forward_velocity_max_mps']):.9g}f\n")
    f.write(f"#define K2_WZ_MAX {float(md['yaw_rate_max_rps']):.9g}f\n")
    f.write(f"#define K2_VY_MAX {fl(float(md['lateral_velocity_max_mps']))}\n")
    f.write("#define K2_DH_MIN 0.0f\n#define K2_DH_MAX 0.0f\n")
    f.write(f"#define K2_VX_RAMP {float(md['gait_velocity_ramp_rate_mps2']):.9g}f\n")
    f.write(f"#define K2_WZ_RAMP {float(md['gait_yaw_rate_ramp_rate_rps2']):.9g}f\n")
    f.write(f"#define K2_HEIGHT_ACTIVE_IN_MARCH "
            f"{1 if md.get('gait_height_active_in_march','0') == '1' else 0}\n")
    f.write(f"#define K2_DH_RAMP {float(md['gait_height_ramp_rate_mps']):.9g}f\n\n")
    # Measured level correction (actual root frame -> level root frame). It
    # feeds BOTH projected_gravity and the gyro in k2_attitude, so omitting it
    # leaves a standing robot reading a few degrees of false tilt.
    lvl = json.load(open("hardware/imu_level_calibration.json"))["root_correction"]
    f.write("static const float K2_LEVEL[9] = {" +
            ", ".join(fl(v) for row in lvl for v in row) + "};\n")
    lim = json.load(open("hardware/joint_limits.json"))
    f.write("static const float K2_QMIN[12] = {" +
            ", ".join(fl(lim[j][0]) for j in C.SIM_ORDER) + "};\n")
    f.write("static const float K2_QMAX[12] = {" +
            ", ".join(fl(lim[j][1]) for j in C.SIM_ORDER) + "};\n")
    f.write(arr("K2_SERVO_ID", [C.JOINT_TO_ID[j] for j in C.SIM_ORDER], "%d"))
    f.write(arr("K2_HOME_RAW", [home[j] for j in C.SIM_ORDER], "%d"))
    f.write(arr("K2_SIGN", [sign[j] for j in C.SIM_ORDER], "%d"))
    f.write(arr("K2_DEFAULT_POS", default_pos))
print("servo ids :", [C.JOINT_TO_ID[j] for j in C.SIM_ORDER])
print("signs     :", [sign[j] for j in C.SIM_ORDER])
print("home_raw  :", [home[j] for j in C.SIM_ORDER])
